//go:build ignore

// Usage: go run gen_errors.go [-o output.go] <btrfsutil.h>
package main

import (
	"bytes"
	"flag"
	"fmt"
	"go/format"
	"os"
	"regexp"
	"strings"
)

const header = `// Code generated by gen_errors.go; DO NOT EDIT.

package btrfsutil

// #cgo LDFLAGS: -lbtrfsutil
// #include <btrfsutil.h>
import "C"

`
const defaultOutFile = "errors_generated.go"

var (
	commentRe = regexp.MustCompile(`(?s)/\*.*?\*/|//[^\n]*`)
	enumRe    = regexp.MustCompile(`(?s)enum\s+btrfs_util_error\s*\{(.*?)\}`)
)

func main() {
	out := flag.String("o", defaultOutFile, "output file")
	flag.Usage = func() {
		fmt.Fprintf(os.Stderr, "usage: %s [-o output.go] <btrfsutil.h>\n", os.Args[0])
	}

	flag.Parse()
	if flag.NArg() != 1 {
		flag.Usage()
		os.Exit(2)
	}

	if err := run(flag.Arg(0), *out); err != nil {
		fmt.Fprintln(os.Stderr, "gen_errors:", err)
		os.Exit(1)
	}
}

func run(headerPath string, outPath string) error {
	src, err := os.ReadFile(headerPath)
	if err != nil {
		return fmt.Errorf("reading header: %w", err)
	}

	names, err := parseEnum(src)
	if err != nil {
		return fmt.Errorf("%s: %w", headerPath, err)
	}

	var buf bytes.Buffer
	buf.WriteString(header)
	buf.WriteString("const (\n")

	seen := make(map[string]string)
	for _, cName := range names {
		goName := toGoName(cName)
		if prev, dup := seen[goName]; dup {
			return fmt.Errorf("%s and %s map to %s", prev, cName, goName)
		}

		seen[goName] = cName
		fmt.Fprintf(&buf, "\t%s ErrorCode = C.%s\n", goName, cName)
	}
	buf.WriteString(")\n")

	formatted, err := format.Source(buf.Bytes())
	if err != nil {
		return fmt.Errorf("formatting generated code: %w\n%s", err, buf.Bytes())
	}
	return os.WriteFile(outPath, formatted, 0o644)
}

func parseEnum(src []byte) ([]string, error) {
	src = commentRe.ReplaceAll(src, nil)

	match := enumRe.FindSubmatch(src)
	if match == nil {
		return nil, fmt.Errorf("enum btrfs_util_error not found")
	}

	var names []string
	for _, item := range strings.Split(string(match[1]), ",") {
		name, _, _ := strings.Cut(item, "=")
		name = strings.TrimSpace(name)
		if name == "" || name == "BTRFS_UTIL_OK" {
			continue
		}

		if !strings.HasPrefix(name, "BTRFS_UTIL_") {
			return nil, fmt.Errorf("unexpected enum member %q", name)
		}

		names = append(names, name)
	}
	if len(names) == 0 {
		return nil, fmt.Errorf("enum btrfs_util_error has no error members")
	}
	return names, nil
}

func toGoName(cName string) string {
	var b strings.Builder
	for part := range strings.SplitSeq(strings.TrimPrefix(cName, "BTRFS_UTIL_"), "_") {
		switch part {
		case "":
			continue
		case "ERROR":
			b.WriteString("Err")
		default:
			b.WriteString(part[:1])
			b.WriteString(strings.ToLower(part[1:]))
		}
	}

	return b.String()
}
